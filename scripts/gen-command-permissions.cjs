// Regenerates src-tauri/permissions/controller-commands.toml from the generate_handler! list in state.rs.
// Run from the repo root: node scripts/gen-command-permissions.cjs
const fs = require('fs');
const src = fs.readFileSync('src-tauri/src/state.rs', 'utf8');
const block = src.split('tauri::generate_handler![')[1].split(']')[0];
const names = [...block.matchAll(/crate::commands::\w+::(\w+)\s*,/g)].map((m) => m[1]);
const lines = names.map((n) => `  "allow-${n.replace(/_/g, '-')}",`).join('\n');
fs.writeFileSync(
  'src-tauri/permissions/controller-commands.toml',
  `# Every app command the controller window may invoke. The projector (presentation) gets none of these.
# Generated by scripts/gen-command-permissions.cjs; tests/invariants.rs fails on any difference from state.rs.
[[set]]
identifier = "controller-commands"
description = "All app commands, for the controller window only"
permissions = [
${lines}
]
`,
);
console.log(`${names.length} commands`);
